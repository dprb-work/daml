//! Snapshot-relative, source-preserving edits of explicitly supplied DAML data.

use crate::{
    Document, FormatOptions, Limits, Node, ParseError, ResolveError, Schemas, SemanticError,
    SemanticErrorKind, SemanticNode, SemanticValue, Span, Value,
};
use std::{borrow::Cow, error::Error, fmt};

/// One operation against the original parsed document, not preceding operations.
#[derive(Debug, Clone, Copy)]
pub enum SourceEdit<'a> {
    /// Replace a complete node, including its assertion and internal comments.
    Replace {
        /// RFC 6901 instance pointer; the empty pointer selects the root.
        path: &'a str,
        /// Explicit supplied value; no completed defaults are serialized.
        value: &'a SemanticNode,
    },
    /// Append an absent mapping field or insert before an original array index.
    Insert {
        /// RFC 6901 pointer; an array's original length appends a value.
        path: &'a str,
        /// Explicit supplied value, rendered through the canonical writer.
        value: &'a SemanticNode,
    },
    /// Remove a mapping entry or array node, retaining adjacent external trivia.
    Remove {
        /// Nonempty RFC 6901 instance pointer.
        path: &'a str,
    },
}

impl<'a> SourceEdit<'a> {
    fn path(self) -> &'a str {
        match self {
            Self::Replace { path, .. } | Self::Insert { path, .. } | Self::Remove { path } => path,
        }
    }
}

/// Finite, cumulative admission bounds for preparing and applying one patch.
///
/// Arithmetic overflow always fails; no sentinel value disables accounting.
/// The canonical semantic writer additionally retains its existing per-value
/// bounds: 100,000 nodes, depth 128, 1 MiB scalar tokens, and 8 MiB output.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SourceEditLimits {
    /// Maximum operations in a batch (default 1,024).
    pub max_operations: usize,
    /// Maximum cumulative admission work units (default 16 MiB).
    ///
    /// The ledger charges: original source bytes once; one unit per operation;
    /// twice each pointer's UTF-8 byte length; one unit per traversed node;
    /// one plus key bytes per mapping entry inspected; and, for each operation
    /// pair, one plus three times the shorter pointer's byte length. The pair
    /// allowance covers logical/byte conflict checks and change ordering.
    /// Supplied semantic values charge one per node, their raw scalar payload
    /// bytes (null/bools use their source spelling lengths), every mapping key,
    /// and every tag name and binding byte. Parent-EOL scans charge every byte
    /// inspected, including both bytes of CRLF, on every scan. Finally, charge
    /// canonical renderer output bytes including its final LF, final replacement
    /// bytes, and whole resulting source bytes once for construction/readmission.
    ///
    /// This is an admission ledger, not a CPU/instruction counter. Known input
    /// work is charged before traversal/rendering. The existing independently
    /// bounded renderer must finish before its actual output size is known;
    /// at most one such render can precede an exhausted-budget rejection.
    /// Application's source comparison and output/readmission are reserved by
    /// the source/output charges during preparation; repeated applications each
    /// reuse the same admitted plan, rather than consuming a shared mutable budget.
    /// Schema-aware application separately uses the resolver's default bounds.
    pub max_work: usize,
    /// Maximum complete authored output bytes, including untouched bytes (8 MiB).
    pub max_output_bytes: usize,
    /// Parser bounds for whole-output readmission (default [`Limits::default`]).
    pub parse: Limits,
}

impl Default for SourceEditLimits {
    fn default() -> Self {
        Self {
            max_operations: 1024,
            max_work: 16 * 1024 * 1024,
            max_output_bytes: 8 * 1024 * 1024,
            parse: Limits::default(),
        }
    }
}

/// Generated bytes replacing one half-open original-source region.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SourceChange {
    /// Original UTF-8 byte region; an insertion has equal start and end.
    pub span: Span,
    /// Newly generated source, without unrelated source or completed defaults.
    pub replacement: String,
}

/// An immutable admitted edit plan borrowing its original source and context.
///
/// Preparing does not validate the final schema: [`Self::apply`] reparses the
/// complete output and, for a contextual patch, resolves it before returning.
/// The plan retains neither edit values nor copies of the original semantic tree.
pub struct SourcePatch<'a> {
    source: &'a str,
    changes: Vec<SourceChange>,
    output_bytes: usize,
    parse: Limits,
    context: Option<(&'a Schemas, Option<&'a str>)>,
}

impl SourcePatch<'_> {
    /// Returns disjoint changes in increasing original-source byte order.
    pub fn changes(&self) -> &[SourceChange] {
        &self.changes
    }

    /// Atomically constructs and admits the complete edited document.
    ///
    /// Every byte of `current_source` must equal the preparation snapshot,
    /// including comments, BOM and trailing whitespace. The original document
    /// is never mutated and no file is written. Defaults used for validation
    /// remain absent from the authored output unless explicitly supplied.
    ///
    /// # Errors
    ///
    /// Returns [`SourceEditError::StaleSource`] before constructing output for a
    /// changed snapshot, or the original parser/schema cause on readmission.
    pub fn apply(&self, current_source: &str) -> Result<Document, SourceEditError> {
        let document = self.apply_syntax(current_source)?;
        if let Some((schemas, expected)) = self.context {
            schemas
                .resolve_with_limits(&document, expected, crate::ResolutionLimits::default())
                .map_err(SourceEditError::Resolve)?;
        }
        Ok(document)
    }

    // Internal consumers that inspect the checked result resolve the returned
    // document themselves. Keep construction/readmission here, without running
    // and discarding the same resolution twice.
    pub(crate) fn apply_syntax(&self, current_source: &str) -> Result<Document, SourceEditError> {
        if current_source != self.source {
            return Err(SourceEditError::StaleSource);
        }
        let mut output = String::with_capacity(self.output_bytes);
        let mut cursor = 0;
        for change in &self.changes {
            output.push_str(&self.source[cursor..change.span.start]);
            output.push_str(&change.replacement);
            cursor = change.span.end;
        }
        output.push_str(&self.source[cursor..]);
        crate::parse_with_limits(output, self.parse).map_err(SourceEditError::Parse)
    }
}

/// A source-edit failure, retaining public parser, semantic and resolver causes.
#[derive(Debug)]
pub enum SourceEditError {
    /// Malformed RFC 6901 syntax or a noncanonical array index.
    InvalidPointer(String),
    /// A target or parent does not exist in the original supplied data.
    PathNotFound(String),
    /// The operation is invalid for its existing target or parent.
    InvalidTarget(String),
    /// Conflicting original zero-based operation indices, before change sorting.
    Conflict {
        /// Earlier original operation index.
        first: usize,
        /// Later original operation index.
        second: usize,
    },
    /// Operation, cumulative work, output size, or checked arithmetic exhausted.
    LimitExceeded,
    /// Current source differs from the preparation snapshot.
    StaleSource,
    /// Whole edited source failed parser readmission.
    Parse(ParseError),
    /// A supplied semantic value cannot be rendered faithfully.
    Semantic(SemanticError),
    /// Whole edited source failed contextual resolution.
    Resolve(ResolveError),
}

impl fmt::Display for SourceEditError {
    fn fmt(&self, out: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidPointer(path) => write!(out, "invalid RFC 6901 instance pointer {path:?}"),
            Self::PathNotFound(path) => {
                write!(out, "no supplied value at instance pointer {path:?}")
            }
            Self::InvalidTarget(path) => write!(out, "invalid source edit target {path:?}"),
            Self::Conflict { first, second } => {
                write!(out, "source edits {first} and {second} conflict")
            }
            Self::LimitExceeded => out.write_str("source edit resource limit exceeded"),
            Self::StaleSource => out.write_str("source changed since edit preparation"),
            Self::Parse(error) => error.fmt(out),
            Self::Semantic(error) => error.fmt(out),
            Self::Resolve(error) => error.fmt(out),
        }
    }
}

impl Error for SourceEditError {
    fn source(&self) -> Option<&(dyn Error + 'static)> {
        match self {
            Self::Parse(error) => Some(error),
            Self::Semantic(error) => Some(error),
            Self::Resolve(error) => Some(error),
            _ => None,
        }
    }
}

impl Document {
    /// Prepares source-preserving operations against this original snapshot.
    ///
    /// Paths select explicit parsed data only, using literal decoded map keys
    /// and canonical nonnegative array indices. Insertions never create parents;
    /// only replacement may select the root. Duplicate, ancestor/descendant and
    /// byte-overlapping targets, including coincident insertions, are rejected.
    /// Untouched source/tree data is borrowed, not copied or semantically rebuilt.
    ///
    /// # Errors
    ///
    /// Returns pointer/target/conflict/resource or semantic rendering errors.
    /// Bound tags require [`Schemas::prepare_source_edits`]. Whole-output parser
    /// admission occurs on [`SourcePatch::apply`], including for an empty batch.
    pub fn prepare_source_edits(
        &self,
        edits: &[SourceEdit<'_>],
        options: FormatOptions,
        limits: SourceEditLimits,
    ) -> Result<SourcePatch<'_>, SourceEditError> {
        prepare(self, None, edits, options, limits)
    }
}

impl Schemas {
    /// Prepares edits using this registry's source spellings for bound assertions.
    ///
    /// Existing source is not initially resolved, so an invalid value can be
    /// repaired. Application reparses and resolves the entire edited document
    /// with `expected` as an additional root obligation, without writing defaults.
    /// Native definitions are not editable through this data-document API.
    ///
    /// # Errors
    ///
    /// Returns the preparation failures of [`Document::prepare_source_edits`],
    /// including unrepresentable assertion bindings. Final schema failures are
    /// returned by [`SourcePatch::apply`], not hidden by successful preparation.
    pub fn prepare_source_edits<'a>(
        &'a self,
        document: &'a Document,
        expected: Option<&'a str>,
        edits: &[SourceEdit<'_>],
        options: FormatOptions,
        limits: SourceEditLimits,
    ) -> Result<SourcePatch<'a>, SourceEditError> {
        prepare(document, Some((self, expected)), edits, options, limits)
    }
}

struct Work {
    remaining: usize,
}

impl Work {
    fn charge(&mut self, amount: usize) -> Result<(), SourceEditError> {
        self.remaining = self
            .remaining
            .checked_sub(amount)
            .ok_or(SourceEditError::LimitExceeded)?;
        Ok(())
    }
}

struct Planned<'a> {
    edit: SourceEdit<'a>,
    span: Span,
    parent: Option<&'a Node>,
    key: Option<Cow<'a, str>>,
    implicit: bool,
}

fn prepare<'a>(
    document: &'a Document,
    context: Option<(&'a Schemas, Option<&'a str>)>,
    edits: &[SourceEdit<'_>],
    options: FormatOptions,
    limits: SourceEditLimits,
) -> Result<SourcePatch<'a>, SourceEditError> {
    if edits.len() > limits.max_operations {
        return Err(SourceEditError::LimitExceeded);
    }
    options.validate().map_err(|error| {
        SourceEditError::Semantic(SemanticError {
            kind: SemanticErrorKind::InvalidLineWidth,
            pointer: String::new(),
            message: error.to_string(),
        })
    })?;
    let mut work = Work {
        remaining: limits.max_work,
    };
    work.charge(document.source().len())?;
    work.charge(edits.len())?;
    let mut plans = Vec::with_capacity(edits.len());
    for edit in edits {
        plans.push(plan(document, *edit, &mut work)?);
    }
    for second in 0..plans.len() {
        for first in 0..second {
            let a = &plans[first];
            let b = &plans[second];
            let compare = a
                .edit
                .path()
                .len()
                .min(b.edit.path().len())
                .checked_mul(3)
                .and_then(|n| n.checked_add(1))
                .ok_or(SourceEditError::LimitExceeded)?;
            work.charge(compare)?;
            if logical_conflict(a.edit.path(), b.edit.path()) || byte_conflict(a.span, b.span) {
                return Err(SourceEditError::Conflict { first, second });
            }
        }
    }
    let removed = plans.iter().try_fold(0usize, |total, plan| {
        total
            .checked_add(plan.span.end - plan.span.start)
            .ok_or(SourceEditError::LimitExceeded)
    })?;
    let retained = document
        .source()
        .len()
        .checked_sub(removed)
        .ok_or(SourceEditError::LimitExceeded)?;
    if retained > limits.max_output_bytes {
        return Err(SourceEditError::LimitExceeded);
    }
    let mut changes = Vec::with_capacity(plans.len());
    let mut generated = 0usize;
    for plan in plans {
        let replacement = match plan.edit {
            SourceEdit::Remove { .. } => String::new(),
            SourceEdit::Replace { value, .. } | SourceEdit::Insert { value, .. } => {
                inspect_value(value, 0, &mut 0, &mut work)?;
                let rendered = match context {
                    Some((schemas, _)) => schemas.format_semantic(value, options),
                    None => crate::format_semantic(value, options),
                }
                .map_err(SourceEditError::Semantic)?;
                work.charge(rendered.len())?;
                let eol = if plan.parent.is_some()
                    && (matches!(plan.edit, SourceEdit::Insert { .. })
                        || rendered
                            .strip_suffix('\n')
                            .expect("canonical semantic output ends in LF")
                            .contains('\n'))
                {
                    parent_eol(document, plan.parent, &mut work)?
                } else {
                    "\n"
                };
                replacement(
                    plan.edit,
                    plan.key.as_deref(),
                    plan.implicit,
                    rendered,
                    eol,
                    limits,
                    &mut work,
                )?
            }
        };
        generated = generated
            .checked_add(replacement.len())
            .ok_or(SourceEditError::LimitExceeded)?;
        changes.push(SourceChange {
            span: plan.span,
            replacement,
        });
    }
    let output_bytes = retained
        .checked_add(generated)
        .ok_or(SourceEditError::LimitExceeded)?;
    if output_bytes > limits.max_output_bytes {
        return Err(SourceEditError::LimitExceeded);
    }
    work.charge(output_bytes)?;
    changes.sort_unstable_by_key(|change| change.span.start);
    Ok(SourcePatch {
        source: document.source(),
        changes,
        output_bytes,
        parse: limits.parse,
        context,
    })
}

fn semantic_error(kind: SemanticErrorKind, path: &str, message: &str) -> SourceEditError {
    SourceEditError::Semantic(SemanticError {
        kind,
        pointer: path.to_owned(),
        message: message.to_owned(),
    })
}

fn plan<'a>(
    document: &'a Document,
    edit: SourceEdit<'a>,
    work: &mut Work,
) -> Result<Planned<'a>, SourceEditError> {
    let path = edit.path();
    work.charge(
        path.len()
            .checked_mul(2)
            .ok_or(SourceEditError::LimitExceeded)?,
    )?;
    if path.is_empty() {
        return if matches!(edit, SourceEdit::Replace { .. }) {
            Ok(Planned {
                edit,
                span: document.root().span,
                parent: None,
                key: None,
                implicit: false,
            })
        } else {
            Err(SourceEditError::InvalidTarget(path.to_owned()))
        };
    }
    if !path.starts_with('/') {
        return Err(SourceEditError::InvalidPointer(path.to_owned()));
    }
    // As with ordinary instance selection, validate every escape before traversal
    // can stop at an absent parent. Decoding remains the shared pointer owner's.
    let mut bytes = path.bytes();
    while let Some(byte) = bytes.next() {
        if byte == b'~' && !matches!(bytes.next(), Some(b'0' | b'1')) {
            return Err(SourceEditError::InvalidPointer(path.to_owned()));
        }
    }
    let (parents, last) = path
        .rsplit_once('/')
        .expect("nonempty admitted pointer contains slash");
    let mut parent = document.root();
    if !parents.is_empty() {
        for part in parents[1..].split('/') {
            let key =
                crate::pointer::decode_segment(part).expect("all pointer escapes were admitted");
            parent = child(document, parent, &key, path, work)?;
        }
    }
    work.charge(1)?;
    let key = crate::pointer::decode_segment(last).expect("all pointer escapes were admitted");
    let mut insertion_key = None;
    let mut implicit = false;
    let span = match &parent.value {
        Value::Mapping(entries) => {
            let mut found = None;
            for entry in entries {
                work.charge(entry.key.end - entry.key.start + 1)?;
                if document.slice(entry.key) == Some(key.as_ref()) {
                    found = Some(entry);
                    break;
                }
            }
            match (edit, found) {
                (SourceEdit::Replace { .. }, Some(entry)) => entry.value.span,
                (SourceEdit::Remove { .. }, Some(entry)) => Span {
                    start: entry.key.start,
                    end: entry.value.span.end,
                },
                (SourceEdit::Insert { .. }, None) => {
                    if !crate::names::valid_key(&key) {
                        return Err(semantic_error(
                            SemanticErrorKind::InvalidKey,
                            path,
                            "mapping key is not representable",
                        ));
                    }
                    implicit = parent.tag.is_some_and(|tag| tag.end == parent.span.end);
                    let at = if implicit {
                        parent.span.end
                    } else {
                        parent.span.end - 1
                    };
                    insertion_key = Some(key);
                    Span { start: at, end: at }
                }
                (SourceEdit::Insert { .. }, Some(_)) => {
                    return Err(SourceEditError::InvalidTarget(path.to_owned()));
                }
                _ => return Err(SourceEditError::PathNotFound(path.to_owned())),
            }
        }
        Value::Sequence(items) => {
            let index = array_index(&key, path)?;
            match edit {
                SourceEdit::Insert { .. } if index <= items.len() => {
                    let at = items
                        .get(index)
                        .map_or(parent.span.end - 1, |node| node.span.start);
                    Span { start: at, end: at }
                }
                SourceEdit::Replace { .. } | SourceEdit::Remove { .. } if index < items.len() => {
                    items[index].span
                }
                _ => return Err(SourceEditError::PathNotFound(path.to_owned())),
            }
        }
        _ => return Err(SourceEditError::InvalidTarget(path.to_owned())),
    };
    Ok(Planned {
        edit,
        span,
        parent: Some(parent),
        key: insertion_key,
        implicit,
    })
}

fn child<'a>(
    document: &Document,
    node: &'a Node,
    key: &str,
    path: &str,
    work: &mut Work,
) -> Result<&'a Node, SourceEditError> {
    work.charge(1)?;
    match &node.value {
        Value::Mapping(entries) => {
            for entry in entries {
                work.charge(entry.key.end - entry.key.start + 1)?;
                if document.slice(entry.key) == Some(key) {
                    return Ok(&entry.value);
                }
            }
        }
        Value::Sequence(items) => {
            if let Some(node) = items.get(array_index(key, path)?) {
                return Ok(node);
            }
        }
        _ => {}
    }
    Err(SourceEditError::PathNotFound(path.to_owned()))
}

fn array_index(key: &str, path: &str) -> Result<usize, SourceEditError> {
    if key.is_empty()
        || (key.len() > 1 && key.starts_with('0'))
        || !key.bytes().all(|byte| byte.is_ascii_digit())
    {
        return Err(SourceEditError::InvalidPointer(path.to_owned()));
    }
    key.parse()
        .map_err(|_| SourceEditError::InvalidPointer(path.to_owned()))
}

fn logical_conflict(a: &str, b: &str) -> bool {
    // Strict RFC 6901 has a unique spelling per decoded token. Raw slash
    // boundaries therefore suffice, including the root and escaped literal keys.
    a == b
        || a.strip_prefix(b).is_some_and(|rest| rest.starts_with('/'))
        || b.strip_prefix(a).is_some_and(|rest| rest.starts_with('/'))
}

fn byte_conflict(a: Span, b: Span) -> bool {
    if a.start == a.end && b.start == b.end {
        a.start == b.start
    } else if a.start == a.end {
        b.start <= a.start && a.start < b.end
    } else if b.start == b.end {
        a.start <= b.start && b.start < a.end
    } else {
        a.start < b.end && b.start < a.end
    }
}

fn inspect_value(
    node: &SemanticNode,
    depth: usize,
    nodes: &mut usize,
    work: &mut Work,
) -> Result<(), SourceEditError> {
    work.charge(1)?;
    *nodes += 1;
    if *nodes > crate::semantic::MAX_NODES
        || (depth >= crate::semantic::MAX_DEPTH
            && matches!(
                &node.value,
                SemanticValue::Mapping(_) | SemanticValue::Sequence(_)
            ))
    {
        return Err(semantic_error(
            SemanticErrorKind::LimitExceeded,
            "",
            "semantic value exceeds canonical writer node/depth bound",
        ));
    }
    if let Some(tag) = &node.tag {
        work.charge(tag.name.len())?;
        if let Some(binding) = &tag.binding {
            work.charge(binding.len())?;
        }
    }
    match &node.value {
        SemanticValue::Null => work.charge(4)?,
        SemanticValue::Bool(value) => work.charge(if *value { 4 } else { 5 })?,
        SemanticValue::Number(value) => work.charge(value.as_str().len())?,
        SemanticValue::String(value) => work.charge(value.len())?,
        SemanticValue::Temporal(value) => work.charge(value.as_str().len())?,
        SemanticValue::Sequence(items) => {
            for item in items {
                inspect_value(item, depth + 1, nodes, work)?;
            }
        }
        SemanticValue::Mapping(fields) => {
            for (key, value) in fields {
                work.charge(key.len())?;
                inspect_value(value, depth + 1, nodes, work)?;
            }
        }
    }
    Ok(())
}

fn parent_eol<'a>(
    document: &'a Document,
    parent: Option<&Node>,
    work: &mut Work,
) -> Result<&'a str, SourceEditError> {
    let Some(parent) = parent else {
        return Ok("\n");
    };
    let source = &document.source()[parent.span.start..parent.span.end];
    for (at, byte) in source.bytes().enumerate() {
        work.charge(1)?;
        if matches!(byte, b'\r' | b'\n') {
            let end =
                crate::source::line_end(source.as_bytes(), at).expect("matched physical newline");
            work.charge(end - at - 1)?;
            return Ok(&source[at..end]);
        }
    }
    Ok("\n")
}

fn replacement(
    edit: SourceEdit<'_>,
    key: Option<&str>,
    implicit: bool,
    mut rendered: String,
    eol: &str,
    limits: SourceEditLimits,
    work: &mut Work,
) -> Result<String, SourceEditError> {
    // The canonical writer always adds one LF. Its payloads are JSON-quoted,
    // including temporal/cron text: remaining physical LFs are structural only.
    rendered.pop();
    let insertion = matches!(edit, SourceEdit::Insert { .. });
    let newlines = rendered.bytes().filter(|byte| *byte == b'\n').count();
    let extra_eol = newlines
        .checked_mul(eol.len() - 1)
        .ok_or(SourceEditError::LimitExceeded)?;
    let mut bytes = rendered
        .len()
        .checked_add(extra_eol)
        .ok_or(SourceEditError::LimitExceeded)?;
    if insertion {
        bytes = bytes
            .checked_add(2 * eol.len())
            .ok_or(SourceEditError::LimitExceeded)?;
        if let Some(key) = key {
            bytes = bytes
                .checked_add(key.len())
                .and_then(|n| n.checked_add(2))
                .ok_or(SourceEditError::LimitExceeded)?;
        }
        if implicit {
            bytes = bytes.checked_add(3).ok_or(SourceEditError::LimitExceeded)?;
        }
    }
    if bytes > limits.max_output_bytes {
        return Err(SourceEditError::LimitExceeded);
    }
    work.charge(bytes)?;
    if !insertion && eol == "\n" {
        return Ok(rendered);
    }
    let mut output = String::with_capacity(bytes);
    if insertion {
        if implicit {
            output.push_str(" {");
        }
        output.push_str(eol);
        if let Some(key) = key {
            output.push_str(key);
            output.push_str(": ");
        }
    }
    let mut lines = rendered.split('\n');
    output.push_str(lines.next().expect("split always has a first item"));
    for line in lines {
        output.push_str(eol);
        output.push_str(line);
    }
    if insertion {
        output.push_str(eol);
        if implicit {
            output.push('}');
        }
    }
    Ok(output)
}
